#!/usr/bin/env node
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entries = [];
for (const source of ["extensions", "extensions.local"]) {
 const dir = join(root, "apps/web/src", source);
 if (!existsSync(dir)) continue;
 for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  if (entry.isDirectory() && existsSync(join(dir, entry.name, "manifest.ts"))) entries.push({ source, id: entry.name });
 }
}
const imports = entries.map((entry, i) => `import manifest${i} from "../../${entry.source}/${entry.id}/manifest";`).join("\n");
writeFileSync(join(root, "apps/web/src/extensions/sdk/manifests.generated.ts"), `// Generated by sync-extension-manifests.mjs.\n${imports}\nexport const INSTALLED_MANIFESTS = [${entries.map((_,i)=>`manifest${i}`).join(", ")}];\n`);
console.log(`Extension manifest index: ${entries.length} declarations`);

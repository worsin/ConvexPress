import {test,expect} from "@playwright/test";
import {writeFile} from "node:fs/promises";

test("published search blocks bind the URL query and preserve independent pagination",async({page},info)=>{
 test.setTimeout(90000);
 const origin=process.env.CONVEXPRESS_SEARCH_ACCEPTANCE_ORIGIN;
 test.skip(!origin,"Requires the owned Website bound to the retained search acceptance fleet");
 if(!origin)return;
 const endpoint=new URL(origin);
 if(endpoint.protocol!=="http:"||!["127.0.0.1","localhost"].includes(endpoint.hostname)||endpoint.username||endpoint.password)throw Error("Expected an owned loopback Website");
 const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
 await page.setViewportSize({width:1440,height:1100});
 await page.goto(new URL("/page/search-results-20260915?q=acceptance&campaign=verification",endpoint).href,{waitUntil:"networkidle"});
 const blocks=page.locator(".cp-search-results"),first=blocks.nth(0),second=blocks.nth(1);
 await expect(blocks).toHaveCount(2);await expect(first.locator(".cp-search-item")).toHaveCount(1);await expect(second.locator(".cp-search-item")).toHaveCount(2);
 await expect(first.getByRole("searchbox")).toHaveValue("acceptance");
 await second.getByRole("link",{name:"Next results"}).click();
 await expect(second.getByRole("link",{name:"First results"})).toBeVisible();
 const secondPosition=JSON.parse(new URL(page.url()).searchParams.get("blockPages")!);
 delete secondPosition["search.query"];
 expect(Object.keys(secondPosition)).toHaveLength(1);
 const secondKey=Object.keys(secondPosition)[0],secondCursor=secondPosition[secondKey];
 const secondTitles=await second.locator("h3").allTextContents();
 await first.getByRole("link",{name:"Next results"}).click();
 await expect(first.getByRole("link",{name:"First results"})).toBeVisible();
 const bothPositions=JSON.parse(new URL(page.url()).searchParams.get("blockPages")!);
 delete bothPositions["search.query"];
 expect(bothPositions[secondKey]).toBe(secondCursor);expect(Object.keys(bothPositions)).toHaveLength(2);
 expect(await second.locator("h3").allTextContents()).toEqual(secondTitles);
 expect(new URL(page.url()).searchParams.get("q")).toBe("acceptance");expect(new URL(page.url()).searchParams.get("campaign")).toBe("verification");
 await page.screenshot({path:info.outputPath("published-independent-search.png"),fullPage:true,animations:"disabled"});
 await first.getByRole("searchbox").fill("zzzznomatch20260915");await first.getByRole("button",{name:"Search",exact:false}).click();
 await expect(first.getByRole("searchbox")).toHaveValue("zzzznomatch20260915");
 await expect(first.locator(".cp-search-item")).toHaveCount(0);await expect(second.locator(".cp-search-item")).toHaveCount(0);
 await expect(first).toContainText("No matches this time.");
 const resetPosition=JSON.parse(new URL(page.url()).searchParams.get("blockPages")??"{}");delete resetPosition["search.query"];expect(resetPosition).toEqual({});expect(new URL(page.url()).searchParams.get("campaign")).toBe("verification");
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:info.outputPath("published-search-empty-mobile.png"),fullPage:true,animations:"disabled"});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await writeFile(info.outputPath("runtime-observations.json"),JSON.stringify({pageErrors:errors,independentBlockCursors:true,querySubmissionResetsAllCursors:true,unrelatedQueryPreserved:true},null,2));
 expect(errors).toEqual([]);
});

#!/usr/bin/env node
/**
 * generate-extension-index.mjs
 *
 * Scans the two extension roots:
 *   - packages/backend/convex/extensions/<id>/schema.ts       (official, tracked)
 *   - packages/backend/convex/extensions.local/<id>/schema.ts (local, gitignored)
 *
 * Emits packages/backend/convex/schema/_extensionsIndex.generated.ts
 * which the main `schema.ts` hub imports + spreads. Every `schema.ts`
 * file in either root is expected to export `tables` (a record of
 * Convex `defineTable(...)` calls).
 *
 * Output shape:
 *   import { tables as <slug>Tables } from "../extensions/<id>/schema";
 *   import { tables as <slug>LocalTables } from "../extensions.local/<id>/schema";
 *   export const extensionTables = { ...<slug>Tables, ...<slug>LocalTables };
 *
 * If no extensions exist on disk, emits `export const extensionTables = {};`
 *
 * Idempotent. Safe to run repeatedly. Output is gitignored.
 *
 * Hooked into package.json scripts:
 *   - predev / predeploy: runs before convex dev / convex deploy
 *   - codegen:extensions: standalone manual run
 */

import { readdirSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const BACKEND_ROOT = resolve(HERE, "..");                 // packages/backend/
const CONVEX_DIR = join(BACKEND_ROOT, "convex");
const OFFICIAL_DIR = join(CONVEX_DIR, "extensions");
const LOCAL_DIR = join(CONVEX_DIR, "extensions.local");
const SCHEMA_DIR = join(CONVEX_DIR, "schema");
const OUT_PATH = join(SCHEMA_DIR, "_extensionsIndex.generated.ts");

/**
 * Convert an extension id (e.g., "case-studies") to a JS-safe identifier
 * prefix (e.g., "caseStudies") for use in import/spread statements.
 */
function toIdentifier(id) {
	const camel = id.replace(/[-_](.)/g, (_, c) => c.toUpperCase());
	// Strip any other unsafe chars; identifier must start with a letter.
	return camel.replace(/[^a-zA-Z0-9_]/g, "");
}

/**
 * List extension folders that contain a schema.ts at the top level.
 * Returns an array of { id, slug, importPath } objects.
 *
 * `root` is the absolute folder path; `relativeFrom` is the path that
 * import statements inside the generated file should resolve against
 * (it lives at convex/schema/_extensionsIndex.generated.ts, so imports
 * to convex/extensions/<id>/schema are "../extensions/<id>/schema").
 */
function findSchemas(root, importPrefix) {
	if (!existsSync(root)) return [];
	const entries = readdirSync(root, { withFileTypes: true });
	const out = [];
	for (const entry of entries) {
		if (!entry.isDirectory()) continue;
		// Skip metadata folders like .gitkeep helpers, node_modules, etc.
		if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
		const schemaPath = join(root, entry.name, "schema.ts");
		if (!existsSync(schemaPath)) continue;
		out.push({
			id: entry.name,
			slug: toIdentifier(entry.name),
			importPath: `${importPrefix}/${entry.name}/schema`,
		});
	}
	return out;
}

function generate() {
	const official = findSchemas(OFFICIAL_DIR, "../extensions");
	const local = findSchemas(LOCAL_DIR, "../extensions.local");

	// Disambiguate identifier collisions between official and local sources
	// by suffixing local identifiers with "Local".
	const officialSeen = new Set(official.map((e) => e.slug));
	for (const ext of local) {
		if (officialSeen.has(ext.slug)) {
			ext.slug = `${ext.slug}Local`;
		}
	}

	const all = [...official, ...local];

	const header = [
		"// AUTO-GENERATED — DO NOT EDIT BY HAND.",
		"// Regenerated by packages/backend/scripts/generate-extension-index.mjs.",
		"// Run `bun run codegen:extensions` (or it runs automatically as predev/predeploy).",
		"//",
		"// Scans convex/extensions/* (official, tracked) AND convex/extensions.local/* (user, gitignored)",
		"// for any folder containing a top-level `schema.ts` that exports `tables`.",
		"// All discovered tables are merged into a single `extensionTables` object",
		"// which the main schema hub spreads into `defineSchema`.",
		"",
	].join("\n");

	if (all.length === 0) {
		const body = "export const extensionTables = {};\n";
		mkdirSync(SCHEMA_DIR, { recursive: true });
		writeFileSync(OUT_PATH, header + body, "utf-8");
		return { official: 0, local: 0, outPath: OUT_PATH };
	}

	const imports = all
		.map((e) => `import { tables as ${e.slug}Tables } from "${e.importPath}";`)
		.join("\n");

	const spreads = all.map((e) => `\t...${e.slug}Tables,`).join("\n");

	const body = [
		imports,
		"",
		"export const extensionTables = {",
		spreads,
		"};",
		"",
	].join("\n");

	mkdirSync(SCHEMA_DIR, { recursive: true });
	writeFileSync(OUT_PATH, header + body, "utf-8");
	return { official: official.length, local: local.length, outPath: OUT_PATH };
}

/**
 * Dashboard contributions: any extension folder with a top-level
 * `dashboard.ts` exporting `pages` and/or `widgets` is merged into
 * convex/schema/_dashboardIndex.generated.ts, which the dashboard
 * extension's registry reads.
 */
function findDashboardContributions(root, importPrefix) {
	if (!existsSync(root)) return [];
	const entries = readdirSync(root, { withFileTypes: true });
	const out = [];
	for (const entry of entries) {
		if (!entry.isDirectory()) continue;
		if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
		if (entry.name === "dashboard") continue; // the registry itself
		const filePath = join(root, entry.name, "dashboard.ts");
		if (!existsSync(filePath)) continue;
		out.push({
			id: entry.name,
			slug: toIdentifier(entry.name),
			importPath: `${importPrefix}/${entry.name}/dashboard`,
		});
	}
	return out;
}

function generateDashboardIndex() {
	const outPath = join(SCHEMA_DIR, "_dashboardIndex.generated.ts");
	const official = findDashboardContributions(OFFICIAL_DIR, "../extensions");
	const local = findDashboardContributions(LOCAL_DIR, "../extensions.local");
	const officialSeen = new Set(official.map((e) => e.slug));
	for (const ext of local) if (officialSeen.has(ext.slug)) ext.slug = `${ext.slug}Local`;
	const all = [...official, ...local];
	const header = [
		"// AUTO-GENERATED — DO NOT EDIT BY HAND.",
		"// Regenerated by packages/backend/scripts/generate-extension-index.mjs.",
		"// Merges every convex/extensions(.local)/<id>/dashboard.ts (exporting `pages` and/or",
		"// `widgets`) into one list the dashboard extension registry reads.",
		"",
	].join("\n");
	const imports = all.map((e) => `import * as ${e.slug}Dashboard from "${e.importPath}";`).join("\n");
	const entries = all
		.map((e) => `\t{ id: "${e.id}", pages: (${e.slug}Dashboard as any).pages ?? [], widgets: (${e.slug}Dashboard as any).widgets ?? [] },`)
		.join("\n");
	const body = [
		imports,
		"",
		"export const extensionDashboardContributions: Array<{ id: string; pages: any[]; widgets: any[] }> = [",
		entries,
		"];",
		"",
	].join("\n");
	mkdirSync(SCHEMA_DIR, { recursive: true });
	writeFileSync(outPath, header + body, "utf-8");
	return all.length;
}

const dashboardCount = generateDashboardIndex();
console.log(`[generate-extension-index] dashboard contributions: ${dashboardCount}`);

const result = generate();
const localCount = result.local;
const officialCount = result.official;
const total = officialCount + localCount;
console.log(
	`[generate-extension-index] wrote ${result.outPath}  ` +
		`(${officialCount} official, ${localCount} local, ${total} total)`,
);

// Extension-owned enablement metadata: scaffolds do not edit core plugin switches.
const pluginEntries = [];
for (const [dir, prefix] of [[OFFICIAL_DIR, "../extensions"], [LOCAL_DIR, "../extensions.local"]]) {
  if (!existsSync(dir)) continue;
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a,b)=>a.name.localeCompare(b.name))) {
    if (entry.isDirectory() && existsSync(join(dir, entry.name, "plugin.ts"))) pluginEntries.push({ id: entry.name, path: `${prefix}/${entry.name}/plugin` });
  }
}
const pluginIds = new Set();
for (const entry of pluginEntries) { if (pluginIds.has(entry.id)) throw new Error(`Duplicate extension plugin: ${entry.id}`); pluginIds.add(entry.id); }
writeFileSync(join(SCHEMA_DIR, "_pluginIndex.generated.ts"), `// AUTO-GENERATED by generate-extension-index.mjs.\n${pluginEntries.map((entry,i)=>`import { plugin as plugin${i} } from "${entry.path}";`).join("\n")}\nexport const extensionPlugins: Array<{id:string;settingsKey:string;defaultEnabled:boolean;parentId?:string}> = [${pluginEntries.map((_,i)=>`plugin${i}`).join(", ")}];\n`);
console.log(`[generate-extension-index] plugin declarations: ${pluginEntries.length}`);

// Search readers are extension-owned so a cloned plugin never reads the
// reference plugin's table or inherits authority from stale indexed content.
const searchEntries = [];
for (const [dir, prefix] of [[OFFICIAL_DIR, "../extensions"], [LOCAL_DIR, "../extensions.local"]]) {
  if (!existsSync(dir)) continue;
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.isDirectory() && existsSync(join(dir, entry.name, "search.ts"))) searchEntries.push({ id: entry.name, path: `${prefix}/${entry.name}/search` });
  }
}
const searchIds = new Set();
for (const entry of searchEntries) {
  if (searchIds.has(entry.id)) throw new Error(`Duplicate extension search source: ${entry.id}`);
  searchIds.add(entry.id);
}
writeFileSync(join(SCHEMA_DIR, "_searchIndex.generated.ts"), `// AUTO-GENERATED by generate-extension-index.mjs.\nimport type { ExtensionSearchSource } from "../search/extensionSources";\n${searchEntries.map((entry, i) => `import { searchSource as source${i} } from "${entry.path}";`).join("\n")}\nexport const extensionSearchSources: readonly ExtensionSearchSource[] = [${searchEntries.map((_, i) => `source${i}`).join(", ")}];\n`);
console.log(`[generate-extension-index] search sources: ${searchEntries.length}`);

const rsvpEntries = [];
for (const [dir, prefix] of [[OFFICIAL_DIR, "../extensions"], [LOCAL_DIR, "../extensions.local"]]) {
  if (!existsSync(dir)) continue;
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.isDirectory() && existsSync(join(dir, entry.name, "rsvpSource.ts"))) rsvpEntries.push({ id: entry.name, path: `${prefix}/${entry.name}/rsvpSource` });
  }
}
const rsvpIds = new Set();
for (const entry of rsvpEntries) { if (rsvpIds.has(entry.id)) throw new Error(`Duplicate extension RSVP source: ${entry.id}`); rsvpIds.add(entry.id); }
writeFileSync(join(SCHEMA_DIR, "_rsvpIndex.generated.ts"), `// AUTO-GENERATED by generate-extension-index.mjs.\nimport type { RsvpSource } from "../canonicalDocuments/rsvpSources";\n${rsvpEntries.map((entry, i) => `import { rsvpSource as source${i} } from "${entry.path}";`).join("\n")}\nexport const extensionRsvpSources: readonly RsvpSource[] = [${rsvpEntries.map((entry, i) => `{ ...source${i}, verifiedAction: ${JSON.stringify(entry.path.slice(3).replace(/\/rsvpSource$/, "/rsvp:submitWithVerification"))} }`).join(", ")}];\n`);
console.log(`[generate-extension-index] RSVP sources: ${rsvpEntries.length}`);

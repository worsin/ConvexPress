/** Offline source gate: never infer writer coverage from a runtime database flag. */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { inspectMediaWriters } from "./media-writer-coverage.mjs";
await import("./check-media-schema.mjs");
await import("./check-post-discovery-writers.mjs");
await import("./check-catalog-source-writers.mjs");
await import("./check-lms-progress-writers.mjs");
await import("./check-wishlist-writers.mjs");
await import("./generate-synced-consumer-coverage.mjs");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const convex = path.join(root, "convex");
const inventory = fs.readFileSync(path.join(convex, "media/referenceInventory.generated.ts"), "utf8");
const owners = new Set();
for (const match of inventory.matchAll(/export const (?:typedMediaReferences|opaqueMediaReferences) = ([\s\S]*?) as const;/g)) {
  for (const table of Object.keys(JSON.parse(match[1]))) owners.add(table);
}
if (owners.size === 0) throw new Error("Media owner inventory was not readable.");
owners.delete("mediaSizes"); owners.delete("mediaMeta");
// These four central boundaries already validate authoring/media and reconcile
// in the same transaction. Their complete source is included in the version.
const trusted = {
  "media/attachmentGuard.ts": ["reconcileCurriculumWrite", "insertWithMediaReferences", "patchWithMediaReferences", "replaceWithMediaReferences", "deleteWithMediaReferences", "insertDynamicWithMediaReferences", "patchDynamicWithMediaReferences", "deleteDynamicWithMediaReferences"],
  "media/references.ts": ["applyReferenceClear"],
  "contentPromotion/shared.ts": ["write"],
  "contentPromotion/operations.ts": ["rollback"],
};
function files(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    if (entry.isDirectory()) return ["__tests__", "_generated"].includes(entry.name) ? [] : files(path.join(directory, entry.name));
    return entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts") ? [path.join(directory, entry.name)] : [];
  }).sort();
}
const violations = [], trustedSources = [];
let writes = 0;
for (const file of files(convex)) {
  const relative = path.relative(convex, file).split(path.sep).join("/");
  const source = fs.readFileSync(file, "utf8");
  const result = inspectMediaWriters(source, { fileName: relative, ownerTables: [...owners], trustedFunctions: trusted[relative] });
  writes += result.writes.length;
  violations.push(...result.violations);
  if (trusted[relative]) trustedSources.push([relative, source]);
}
if (violations.length) {
  for (const item of violations) console.error(`${item.fileName}:${item.line}: ${item.reason} (${item.operation})`);
  throw new Error(`Media writer coverage refused ${violations.length} unguarded or unresolved database writes.`);
}
const semanticFiles = ["_devPurge.ts", "media/referenceExtraction.ts", "media/referencePolicy.ts", "media/referenceScan.ts", "media/reverseIndex.ts", "media/reverseBackfill.ts"];
const hash = crypto.createHash("sha256").update(JSON.stringify({ inventory, trusted, trustedSources, semantics: semanticFiles.map(file => [file, fs.readFileSync(path.join(convex, file), "utf8")]), parser: fs.readFileSync(new URL("./media-writer-coverage.mjs", import.meta.url), "utf8") })).digest("hex");
const target = path.join(convex, "media/writerCoverage.generated.ts");
const output = `// Generated by scripts/generate-media-writer-coverage.mjs. Do not edit.\nexport const MEDIA_WRITER_COVERAGE_VERSION = "media-edges-${hash.slice(0, 24)}";\nexport const MEDIA_WRITER_OWNER_COUNT = ${owners.size};\n`;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("Media writer coverage is stale. Regenerate and review the changed central boundaries before deployment.");
} else fs.writeFileSync(target, output);
console.log(`Media writer coverage: ${writes} classified writes, ${owners.size} owner tables, no bypasses.`);

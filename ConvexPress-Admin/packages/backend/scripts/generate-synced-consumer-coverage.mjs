import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("../convex/", import.meta.url));
const permitNames = new Set(["permitValidatedCanonicalAuthoringWrite", "permitValidatedLegacyRecoveryWrite"]);
const allowed = new Set(["snapshot", "commit", "duplicateDocument", "recoverLegacyDocument", "setDocumentSettings", "writePromotedCanonicalDocument"]);
function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory()
    ? ["__tests__", "_generated"].includes(entry.name) ? [] : files(path.join(dir, entry.name))
    : entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts") ? [path.join(dir, entry.name)] : []);
}
let calls = 0;
for (const file of files(root)) {
  const source = fs.readFileSync(file, "utf8");
  if (![...permitNames].some(name => source.includes(name))) continue;
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true), aliases = new Set(permitNames);
  for (const node of ast.statements) if (ts.isImportDeclaration(node) && node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings))
    for (const item of node.importClause.namedBindings.elements) if (permitNames.has(item.propertyName?.text ?? item.name.text)) aliases.add(item.name.text);
  function visit(node) {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && aliases.has(node.expression.text)) {
      let owner = node.parent;
      while (owner && !ts.isFunctionDeclaration(owner)) owner = owner.parent;
      if (path.relative(root, file) !== "canonicalDocuments/service.ts" || !owner?.name || !allowed.has(owner.name.text))
        throw Error(`Unreviewed canonical write permit at ${path.relative(root, file)}:${ast.getLineAndCharacterOfPosition(node.getStart()).line + 1}`);
      calls++;
    }
    ts.forEachChild(node, visit);
  }
  visit(ast);
}
// Hash the reviewed central boundaries, rather than accepting a DB flag as
// evidence that a newer writer/resolver implementation preserves the index.
const reviewed = [
  "helpers/authoringVersionFence.ts", "media/attachmentGuard.ts", "media/references.ts",
  "contentPromotion/shared.ts", "contentPromotion/operations.ts", "canonicalDocuments/service.ts",
  "canonicalDocuments/contactDocuments.ts", "canonicalDocuments/foundation/syncedContent.ts",
  "canonicalDocuments/foundation/syncedOccurrences.ts", "syncedBlocks/model.ts", "syncedBlocks/content.ts",
  "syncedBlocks/refresh.ts", "syncedBlocks/occurrences.ts", "syncedBlocks/consumers.ts",
  "syncedBlocks/consumerWrites.ts", "syncedBlocks/consumerIndex.ts", "syncedBlocks/consumerIndexState.ts",
  "schema/syncedBlocks.ts",
  "canonicalDocuments/contactProjection.ts", "canonicalDocuments/contactDefinitions.ts",
  "canonicalDocuments/contactFields.ts", "canonicalDocuments/contactMessaging.ts",
  "canonicalDocuments/displayContext.ts",
];
const digest = crypto.createHash("sha256").update(JSON.stringify(reviewed.map(file => [file, fs.readFileSync(path.join(root, file), "utf8")]))).digest("hex");
const text = `// Generated by scripts/generate-synced-consumer-coverage.mjs.\nexport const SYNCED_CONSUMER_INDEX_VERSION = "synced-consumers-${digest.slice(0, 24)}";\n`;
const target = path.join(root, "syncedBlocks/consumerIndexVersion.generated.ts");
if (process.argv.includes("--check")) { if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) throw Error("Reusable consumer writer coverage is stale. Review changed boundaries and regenerate."); }
else fs.writeFileSync(target, text);
console.log(`Reusable consumer coverage: ${calls} reviewed canonical permit calls; ${reviewed.length} versioned boundaries.`);

#!/usr/bin/env bun
/**
 * Generates exact document validators (table fields + _id + _creationTime) for
 * return validators, one companion module per schema module:
 *
 *   convex/schema/posts.ts            → convex/schema/posts.docs.generated.ts       (postsDocs)
 *   convex/extensions/events/schema.ts → convex/extensions/events/schema.docs.generated.ts (eventsExtensionDocs)
 *
 * Each companion imports only its own schema module, so a function that returns
 * `kb_articles` documents depends on schema/kb.ts and nothing else. A single
 * hub importing every table (the first design) put every schema module, the
 * extension index and their imports into the dependency graph of 135 function
 * modules and produced initialization cycles.
 *
 * Also writes scripts/typing/table-docs-manifest.json ({ table: { module,
 * exportName } }) for infer-return-validators.ts. Companions use multi-dot
 * names, so Convex does not treat them as function modules.
 *
 * Run from packages/backend: bun scripts/typing/generate-table-docs.ts [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const backendDir = resolve(import.meta.dir, "..", "..");
const convexDir = join(backendDir, "convex");
const manifestPath = join(backendDir, "scripts", "typing", "table-docs-manifest.json");
const check = process.argv.includes("--check");

type Source = { mapName: string; importFrom: string; schemaModule: string; companion: string; exportName: string };
const sources: Source[] = [];

const camel = (s: string) => s.replace(/[-_]([a-z0-9])/g, (_, c: string) => c.toUpperCase());

// Core schema modules, as composed by the root schema.
const rootSchema = readFileSync(join(convexDir, "schema.ts"), "utf8");
const spreads = new Set([...rootSchema.matchAll(/^\s*\.\.\.(\w+),\s*$/gm)].map((m) => m[1]));
for (const m of rootSchema.matchAll(/^import\s*\{\s*(\w+)\s*\}\s*from\s*"\.\/schema\/([^"]+)";/gm)) {
  const [, mapName, mod] = m;
  if (!spreads.has(mapName) || mod.startsWith("_")) continue; // generated indexes handled below
  sources.push({
    mapName,
    importFrom: `./${mod}`,
    schemaModule: `schema/${mod}`,
    companion: `schema/${mod}.docs.generated`,
    exportName: `${camel(mod)}Docs`,
  });
}
// Extension schema modules, as discovered by the extension index.
const extIndex = readFileSync(join(convexDir, "schema", "_extensionsIndex.generated.ts"), "utf8");
for (const m of extIndex.matchAll(/^import\s*\{\s*tables as (\w+)\s*\}\s*from\s*"\.\.\/(extensions(?:\.local)?\/([^/"]+))\/schema";/gm)) {
  const [, mapName, dir, name] = m;
  sources.push({
    mapName,
    importFrom: "./schema",
    schemaModule: `${dir}/schema`,
    companion: `${dir}/schema.docs.generated`,
    exportName: `${camel(name)}ExtensionDocs`,
  });
}

const isIdent = (s: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s);
const manifest: Record<string, { module: string; exportName: string }> = {};
const outputs: [string, string][] = [];

for (const s of sources) {
  const mod = (await import(join(convexDir, `${s.schemaModule}.ts`))) as Record<string, Record<string, { validator: { kind?: string; json?: { type?: string } } }>>;
  const tables = s.importFrom === "./schema" ? mod.tables : mod[s.mapName];
  if (!tables) throw new Error(`${s.schemaModule}: export ${s.importFrom === "./schema" ? "tables" : s.mapName} not found`);
  const names = Object.keys(tables).sort();
  const objectTables = names.filter((t) => tables[t].validator.json?.type === "object");
  const unionTables = names.filter((t) => tables[t].validator.json?.type !== "object");
  const importName = s.importFrom === "./schema" ? "tables" : s.mapName;
  const docValidatorRel = s.schemaModule.startsWith("schema/") ? "./docValidator" : "../../schema/docValidator";
  const lines = [
    "// GENERATED by scripts/typing/generate-table-docs.ts. Do not edit.",
    `// Exact document validators for the tables defined in ${s.schemaModule}.ts.`,
    ...(unionTables.length ? [`// Union-typed tables (validated inline where returned): ${unionTables.join(", ")}`] : []),
    `import { docValidator } from "${docValidatorRel}";`,
    `import { ${importName} } from "${s.importFrom}";`,
    "",
    `export const ${s.exportName} = {`,
    ...objectTables.map((t) => {
      const key = isIdent(t) ? t : JSON.stringify(t);
      const access = isIdent(t) ? `${importName}.${t}` : `${importName}[${JSON.stringify(t)}]`;
      return `  ${key}: docValidator(${JSON.stringify(t)}, ${access}.validator),`;
    }),
    "};",
    "",
  ];
  outputs.push([join(convexDir, `${s.companion}.ts`), lines.join("\n")]);
  for (const t of objectTables) manifest[t] = { module: s.companion, exportName: s.exportName };
}

const helper = `// GENERATED by scripts/typing/generate-table-docs.ts. Do not edit.
import { v, type PropertyValidators } from "convex/values";

/** A table's stored-document validator: its fields plus Convex's system fields. */
export function docValidator<TableName extends string, Fields extends PropertyValidators>(
  tableName: TableName,
  validator: { fields: Fields },
) {
  return v.object({ ...validator.fields, _id: v.id(tableName), _creationTime: v.number() });
}
`;
outputs.push([join(convexDir, "schema", "docValidator.ts"), helper]);
outputs.push([manifestPath, `${JSON.stringify(manifest, null, 2)}\n`]);

if (check) {
  const stale = outputs.filter(([p, c]) => !existsSync(p) || readFileSync(p, "utf8") !== c).map(([p]) => p);
  if (stale.length) {
    console.error(`stale table docs:\n  ${stale.join("\n  ")}\nRun bun scripts/typing/generate-table-docs.ts`);
    process.exit(1);
  }
  console.log(`table docs up to date (${Object.keys(manifest).length} tables, ${sources.length} modules)`);
} else {
  for (const [p, c] of outputs) writeFileSync(p, c);
  console.log(`table docs written: ${Object.keys(manifest).length} tables across ${sources.length} schema modules`);
}

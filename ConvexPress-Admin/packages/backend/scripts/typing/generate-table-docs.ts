#!/usr/bin/env bun
/**
 * Generates convex/schema/tableDocs.generated.ts: one exact document validator
 * (table fields + _id + _creationTime) per object-typed table, built from the
 * table definitions themselves so it can never drift from the schema.
 *
 * Return validators use these (`returns: v.array(tableDocs.posts)`) instead of
 * convex-helpers' `doc(schema, table)`, which instantiates the whole schema
 * type at every use and re-introduces TS2589 on a 327-table schema.
 *
 * The file uses a multi-dot name so Convex does not treat it as a function
 * module. Run from packages/backend:
 *   bun scripts/typing/generate-table-docs.ts [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const backendDir = resolve(import.meta.dir, "..", "..");
const convexDir = join(backendDir, "convex");
const outPath = join(convexDir, "schema", "tableDocs.generated.ts");
const check = process.argv.includes("--check");

const rootSchema = readFileSync(join(convexDir, "schema.ts"), "utf8");
// Every table map the root schema composes: `import { postTables } from "./schema/posts";`
const imports = [...rootSchema.matchAll(/^import\s*\{\s*(\w+)\s*\}\s*from\s*"\.\/schema\/([^"]+)";/gm)].map((m) => ({
  name: m[1],
  path: m[2],
}));
const spreads = new Set([...rootSchema.matchAll(/^\s*\.\.\.(\w+),\s*$/gm)].map((m) => m[1]));
const maps = imports.filter((i) => spreads.has(i.name));

type FieldType = { type: string; value?: unknown };
const schemaModule = (await import(join(convexDir, "schema.ts"))) as { default: { export(): string } };
const exported = JSON.parse(schemaModule.default.export()) as { tables: { tableName: string; documentType: FieldType }[] };
const objectTables = exported.tables
  .filter((t) => t.documentType.type === "object")
  .map((t) => t.tableName)
  .sort();
const skipped = exported.tables.filter((t) => t.documentType.type !== "object").map((t) => t.tableName);

const isIdent = (s: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s);
const lines = [
  "// GENERATED by scripts/typing/generate-table-docs.ts. Do not edit.",
  "// Exact document validators (fields + system fields) for return validators.",
  'import { v, type PropertyValidators } from "convex/values";',
  ...maps.map((m) => `import { ${m.name} } from "./${m.path}";`),
  "",
  "const tables = {",
  ...maps.map((m) => `  ...${m.name},`),
  "};",
  "",
  "function docValidator<TableName extends string, Fields extends PropertyValidators>(",
  "  tableName: TableName,",
  "  validator: { fields: Fields },",
  ") {",
  "  return v.object({ ...validator.fields, _id: v.id(tableName), _creationTime: v.number() });",
  "}",
  "",
  "export const tableDocs = {",
  ...objectTables.map((t) => {
    const key = isIdent(t) ? t : JSON.stringify(t);
    const access = isIdent(t) ? `tables.${t}` : `tables[${JSON.stringify(t)}]`;
    return `  ${key}: docValidator(${JSON.stringify(t)}, ${access}.validator),`;
  }),
  "};",
  "",
];
if (skipped.length) lines.splice(2, 0, `// Union-typed tables (expanded inline where returned): ${skipped.join(", ")}`);
const content = lines.join("\n");

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== content) {
    console.error("tableDocs.generated.ts is stale — run bun scripts/typing/generate-table-docs.ts");
    process.exit(1);
  }
  console.log(`tableDocs.generated.ts up to date (${objectTables.length} tables)`);
} else {
  writeFileSync(outPath, content);
  console.log(`tableDocs.generated.ts written (${objectTables.length} tables, ${skipped.length} union-typed skipped)`);
}

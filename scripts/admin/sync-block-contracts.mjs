/** Copy existing pure editor schemas into the backend-safe catalog; no editor/renderer imports. */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const admin=resolve(root,'ConvexPress-Admin');
const web=resolve(admin,'apps/web/src');
const out=resolve(admin,'packages/blocks-catalog/src/generated');
const check=process.argv.includes('--check');
const outputs=new Map();
function schemaFile(source,target) {
 const text=readFileSync(source,'utf8');
 const imports=[...text.matchAll(/from\s+["']([^"']+)["']/g)].map(m=>m[1]);
 if(imports.some(id=>id!=='zod')) throw new Error(`Schema must be runtime-independent: ${source}`);
 outputs.set(target,text);
}
schemaFile(resolve(web,'lib/blocks/schemas.ts'),'core.ts');
const registry=readFileSync(resolve(web,'lib/blocks/registry.tsx'),'utf8');
const core=[...registry.matchAll(/name:\s*"(core\/[^\"]+)"[\s\S]*?schema:\s*(\w+)/g)];
if(core.length!==38) throw new Error('Core registry shape changed; review schema extraction');
const imports=['import type { z } from "zod";','import * as core from "./core";'];
const definitions=core.map(m=>`${JSON.stringify(m[1])}: { schema: core.${m[2]} }`);
let discovered=0;
for(const folderRoot of ['blocks','blocks.local']) {
 const dir=resolve(web,folderRoot);
 if(!existsSync(dir)) continue;
 for(const dirent of readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))) {
  if(!dirent.isDirectory()||dirent.name.startsWith('_')) continue;
  const source=resolve(dir,dirent.name);
  if(!existsSync(resolve(source,'manifest.tsx'))) continue;
  const metadata=JSON.parse(readFileSync(resolve(source,'block.json'),'utf8'));
  const manifest=readFileSync(resolve(source,'manifest.tsx'),'utf8');
  const symbol=manifest.match(/schema:\s*(\w+)/)?.[1];
  const name=manifest.match(/name:\s*"([^"]+)"/)?.[1];
  if(!symbol||name!==metadata.name) throw new Error(`Invalid schema registration: ${source}`);
  const target=`${folderRoot.replace('.','-')}-${dirent.name}`;
  schemaFile(resolve(source,'schema.ts'),`${target}.ts`);
  // Ready renderer contracts must have the exact same validation source.
  const website=resolve(root,'ConvexPress-Website/apps/web/src',folderRoot,dirent.name,'schema.ts');
  if(metadata.rendererStatus==='ready'&&(!existsSync(website)||readFileSync(website,'utf8')!==readFileSync(resolve(source,'schema.ts'),'utf8'))) throw new Error(`Admin/Website schema drift: ${metadata.name}`);
  const alias=`schema${discovered++}`;
  imports.push(`import { ${symbol} as ${alias} } from "./${target}";`);
  definitions.push(`${JSON.stringify(metadata.name)}: { schema: ${alias}, metadata: ${JSON.stringify({name:metadata.name,title:metadata.title,description:metadata.description,category:metadata.category,aiHints:metadata.aiHints})} }`);
 }
}
outputs.set('definitions.ts',`// Generated by scripts/admin/sync-block-contracts.mjs. Do not edit.\n${imports.join('\n')}\nexport const BLOCK_DEFINITIONS: Record<string, { schema: z.ZodType; metadata?: { name: string; title: string; description: string; category: string; aiHints?: { useFor?: string; avoid?: string } } }> = {\n${definitions.join(',\n')}\n};\n`);
for(const [name,text] of outputs) {
 const path=resolve(out,name);
 if(check) { if(!existsSync(path)||readFileSync(path,'utf8')!==text) throw new Error(`Generated block contract stale: ${name}. Run bun run sync:blocks.`); }
 else { mkdirSync(dirname(path),{recursive:true});writeFileSync(path,text); }
}
console.log(`Block contracts ${check?'checked':'generated'} (${core.length} core + ${discovered} discovered schemas).`);
